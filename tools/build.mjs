// Builds the deployable app.html from app.dev.html.
//
//   npm run build          write app.html
//   npm run build:check    exit 1 if app.html is stale (run by `npm test`)
//
// app.dev.html is the source: it runs as-is in a browser, transpiling its JSX block with
// in-browser Babel, so editing it still needs no build step. Shipping it that way costs every
// visitor a ~3 MB Babel download plus ~2.5 s of transpiling on each cold start (several times
// that on a phone), and it forces the Content-Security-Policy to allow 'unsafe-eval' and
// 'unsafe-inline' scripts, which leaves the CSP almost no XSS protection.
//
// The build compiles the JSX block with esbuild, inlines the result, drops the Babel script,
// and pins script-src to hashes of the page's inline scripts plus the exact CDN files. The
// output is still a single self-contained HTML file.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { transform } from 'esbuild';
import { REPO_ROOT } from './test/lib/harness.mjs';

const SRC = join(REPO_ROOT, 'app.dev.html');
const OUT = join(REPO_ROOT, 'app.html');
const checkOnly = process.argv.includes('--check');

const fail = (msg) => { console.error('build: ' + msg); process.exit(2); };
// The HTML parser turns CRLF into LF before a browser hashes inline script text, so hash
// (and write) LF regardless of how git checked the source out.
let html = readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');

// ── compile the JSX block ────────────────────────────────────────────────────
const OPEN = '<script type="text/babel">';
const open = html.indexOf(OPEN);
if (open === -1) fail('no <script type="text/babel"> block in app.dev.html');
const start = open + OPEN.length;
const end = html.indexOf('</script>', start);
if (end === -1) fail('unterminated babel script block');

let compiled;
try {
  ({ code: compiled } = await transform(html.slice(start, end), {
    loader: 'jsx',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
  }));
} catch (e) {
  // Map esbuild's line numbers back onto app.dev.html
  const offset = html.slice(0, start).split('\n').length - 1;
  fail(String(e.message).replace(/<stdin>:(\d+):/g, (_, n) => `app.dev.html:${Number(n) + offset}:`));
}
// "</script" inside a string would end the inline script early. Only strings or regexes can
// contain it, where the escaped form means the same thing.
compiled = compiled.replace(/<\/script/gi, '<\\/script').trim();
html = html.slice(0, open) + '<script>' + compiled + '</script>' + html.slice(end + '</script>'.length);

// ── drop in-browser Babel ────────────────────────────────────────────────────
const babelTag = /\s*<script[^>]*src="https:\/\/unpkg\.com\/@babel\/standalone@[^"]*"[^>]*><\/script>/;
if (!babelTag.test(html)) fail('Babel <script> tag not found');
html = html.replace(babelTag, '');

// ── build id: content hash, embedded for the in-app "new version available" check ──
const PLACEHOLDER = '__SATLEDGER_BUILD_ID__';
if (!html.includes(PLACEHOLDER)) fail('build id placeholder not found');
const buildId = createHash('sha256').update(html, 'utf8').digest('hex').slice(0, 16);
html = html.replace(PLACEHOLDER, buildId);
const versionJson = JSON.stringify({ build: buildId }) + '\n';

// ── CSP: hashes instead of 'unsafe-inline' / 'unsafe-eval' ───────────────────
const inline = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]);
if (inline.length < 2) fail(`expected at least 2 inline scripts, found ${inline.length}`);
const hashes = inline.map(s => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`);
const cdn = [...html.matchAll(/<script[^>]*src="(https:\/\/unpkg\.com\/[^"]+)"/g)].map(m => m[1]);
if (cdn.length !== 2) fail(`expected the 2 React CDN scripts, found ${cdn.length}`);
// static.cloudflareinsights.com: the Cloudflare Web Analytics beacon, which Pages injects as
// an external script carrying its own SRI. Cloudflare's per-request inline JS-detections
// script can't be hashed and stays blocked.
const scriptSrc = ["'self'", ...hashes, ...cdn, 'https://accounts.google.com/gsi/client', 'https://static.cloudflareinsights.com'].join(' ');
const cspRe = /(<meta http-equiv="Content-Security-Policy" content="[^"]*?)script-src [^;]*;/;
if (!cspRe.test(html)) fail('CSP script-src directive not found');
html = html.replace(cspRe, `$1script-src ${scriptSrc};`);

// ── mark the output as generated (after <head>: a comment before the doctype would
// put the page in quirks mode) ───────────────────────────────────────────────
html = html.replace('<head>', '<head>\n  <!-- GENERATED by `npm run build` from app.dev.html. Edit app.dev.html, not this file. -->');

const VERSION = join(REPO_ROOT, 'version.json');
if (checkOnly) {
  const read = p => { try { return readFileSync(p, 'utf8').replace(/\r\n/g, '\n'); } catch { return ''; } };
  if (read(OUT) !== html || read(VERSION) !== versionJson) {
    console.error('build: app.html / version.json are out of date with app.dev.html. Run `npm run build` and commit the result.');
    process.exit(1);
  }
  console.log(`OK — app.html is up to date with app.dev.html (build ${buildId})`);
} else {
  writeFileSync(OUT, html);
  writeFileSync(VERSION, versionJson);
  const kb = n => (Buffer.byteLength(n) / 1024).toFixed(0) + ' KB';
  console.log(`built app.html (${kb(html)}; compiled script ${kb(compiled)}), build ${buildId}`);
}
